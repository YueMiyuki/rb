/// `-C metadata` of the `tf` library in a verbose build log
fn tf_metadata(log: &str) -> String {
    let line = log
        .lines()
        .find(|l| l.contains("--crate-name tf ") && l.contains("--crate-type lib"))
        .unwrap_or_else(|| panic!("tf was not compiled:\n{log}"));
    line.split("metadata=")
        .nth(1)
        .unwrap()
        .split(['\'', ' '])
        .next()
        .unwrap()
        .to_owned()
}

#[test]
fn edits_keep_crate_identity_for_incremental_compilation() {
    let p = Project::testing();
    let before = tf_metadata(&p.ok(&["build", "-v", "-p", "tf"]));
    let lib = p.ws().join("tf/src/lib.rs");
    let src = std::fs::read_to_string(&lib).unwrap();
    std::fs::write(&lib, src.replace("a + b", "a.wrapping_add(b).wrapping_add(0)")).unwrap();
    let after = tf_metadata(&p.ok(&["build", "-v", "-p", "tf"]));
    assert_eq!(before, after, "rustc's incremental cache is keyed by -C metadata");
    let sessions = std::fs::read_dir(p.ws().join("target/rb/debug/host/incremental"))
        .unwrap()
        .filter(|e| e.as_ref().unwrap().file_name().to_string_lossy().starts_with("tf-"))
        .count();
    assert_eq!(
        sessions, 2,
        "one incremental directory each for the tf lib and bin, reused across the edit"
    );

    // The binary reflects the edit, and reverting restores the previous version from the store
    let out = p.rb(&["run", "-q", "-p", "tf"]);
    assert_eq!(String::from_utf8_lossy(&out.stdout).trim(), "3");
    std::fs::write(&lib, &src).unwrap();
    let log = p.ok(&["build", "-p", "tf"]);
    assert!(log.contains("(0 compiled"), "{log}");
}

