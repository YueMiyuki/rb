#[test]
fn tree_matches_cargo_for_a_path_dep() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().canonicalize().unwrap();
    let app = root.join("app");
    let lib = root.join("lib");
    std::fs::create_dir_all(app.join("src")).unwrap();
    std::fs::create_dir_all(lib.join("src")).unwrap();
    std::fs::write(app.join("src/main.rs"), "fn main() {}\n").unwrap();
    std::fs::write(lib.join("src/lib.rs"), "\n").unwrap();
    std::fs::write(
        lib.join("Cargo.toml"),
        "[package]\nname = \"mylib\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    std::fs::write(
        app.join("Cargo.toml"),
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\nmylib = { path = \"../lib\" }\n",
    )
    .unwrap();
    let cargo = Command::new("cargo")
        .args(["tree", "--offline", "--manifest-path"])
        .arg(app.join("Cargo.toml"))
        .current_dir(&app)
        .output()
        .unwrap();
    if !cargo.status.success() {
        let lock = Command::new("cargo")
            .args(["generate-lockfile"])
            .current_dir(&app)
            .output()
            .unwrap();
        assert!(lock.status.success(), "{}", String::from_utf8_lossy(&lock.stderr));
    }
    let cargo = Command::new("cargo")
        .args(["tree", "--charset", "ascii"])
        .current_dir(&app)
        .output()
        .unwrap();
    let rb = Command::new(env!("CARGO_BIN_EXE_rb"))
        .args(["tree", "--charset", "ascii", "--offline", "--color", "never"])
        .current_dir(&app)
        .env("RB_HOME", root.join("home"))
        .env("RB_STORE_DIR", root.join("store"))
        .env("RB_COMPACT", "off")
        .env_remove("RUSTC_WRAPPER")
        .output()
        .unwrap();
    let cargo_text = String::from_utf8_lossy(&cargo.stdout);
    let rb_text = String::from_utf8_lossy(&rb.stdout);
    assert!(cargo.status.success(), "{}", String::from_utf8_lossy(&cargo.stderr));
    assert!(rb.status.success(), "{}\n{rb_text}", String::from_utf8_lossy(&rb.stderr));
    assert_eq!(rb_text.trim(), cargo_text.trim(), "rb:\n{rb_text}\ncargo:\n{cargo_text}");
    let cargo_none = Command::new("cargo")
        .args(["tree", "--prefix", "none"])
        .current_dir(&app)
        .output()
        .unwrap();
    let rb_none = Command::new(env!("CARGO_BIN_EXE_rb"))
        .args(["tree", "--prefix", "none", "--offline", "--color", "never"])
        .current_dir(&app)
        .env("RB_HOME", root.join("home"))
        .env("RB_STORE_DIR", root.join("store"))
        .env("RB_COMPACT", "off")
        .output()
        .unwrap();
    assert!(cargo_none.status.success() && rb_none.status.success());
    assert_eq!(
        String::from_utf8_lossy(&rb_none.stdout).trim(),
        String::from_utf8_lossy(&cargo_none.stdout).trim()
    );
    std::fs::write(
        app.join("Cargo.toml"),
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dev-dependencies]\nmylib = { path = \"../lib\" }\n",
    )
    .unwrap();
    let _ = std::fs::remove_file(app.join("Cargo.lock"));
    let normal = Command::new(env!("CARGO_BIN_EXE_rb"))
        .args(["tree", "--charset", "ascii", "--offline", "--color", "never"])
        .current_dir(&app)
        .env("RB_HOME", root.join("home"))
        .env("RB_STORE_DIR", root.join("store"))
        .env("RB_COMPACT", "off")
        .output()
        .unwrap();
    let dev = Command::new(env!("CARGO_BIN_EXE_rb"))
        .args(["tree", "--edges", "dev", "--charset", "ascii", "--offline", "--color", "never"])
        .current_dir(&app)
        .env("RB_HOME", root.join("home"))
        .env("RB_STORE_DIR", root.join("store"))
        .env("RB_COMPACT", "off")
        .output()
        .unwrap();
    let normal_text = String::from_utf8_lossy(&normal.stdout);
    let dev_text = String::from_utf8_lossy(&dev.stdout);
    assert!(normal.status.success() && !normal_text.contains("mylib"), "{normal_text}");
    assert!(
        dev.status.success() && dev_text.contains("mylib"),
        "{dev_text}\n{}",
        String::from_utf8_lossy(&dev.stderr)
    );
    std::fs::write(
        app.join("Cargo.toml"),
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\nmylib = { path = \"../lib\" }\n",
    )
    .unwrap();
    let _ = std::fs::remove_file(app.join("Cargo.lock"));
    let cargo_inv = Command::new("cargo")
        .args(["tree", "-i", "mylib", "--prefix", "none"])
        .current_dir(&app)
        .output()
        .unwrap();
    let rb_inv = Command::new(env!("CARGO_BIN_EXE_rb"))
        .args(["tree", "--invert", "mylib", "--prefix", "none", "--offline", "--color", "never"])
        .current_dir(&app)
        .env("RB_HOME", root.join("home"))
        .env("RB_STORE_DIR", root.join("store"))
        .env("RB_COMPACT", "off")
        .output()
        .unwrap();
    assert!(cargo_inv.status.success(), "{}", String::from_utf8_lossy(&cargo_inv.stderr));
    assert!(rb_inv.status.success(), "{}", String::from_utf8_lossy(&rb_inv.stderr));
    assert_eq!(
        String::from_utf8_lossy(&rb_inv.stdout).trim(),
        String::from_utf8_lossy(&cargo_inv.stdout).trim()
    );
}

#[test]
fn tree_format_matches_cargo() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().canonicalize().unwrap();
    let app = root.join("app");
    let lib = root.join("lib");
    std::fs::create_dir_all(app.join("src")).unwrap();
    std::fs::create_dir_all(lib.join("src")).unwrap();
    std::fs::write(app.join("src/main.rs"), "fn main() {}\n").unwrap();
    std::fs::write(lib.join("src/lib.rs"), "\n").unwrap();
    std::fs::write(
        lib.join("Cargo.toml"),
        "[package]\nname = \"my-lib\"\nversion = \"0.1.0\"\nedition = \"2021\"\nlicense = \"MIT\"\nrepository = \"https://example.com/lib\"\n\n[features]\ndefault = [\"a\"]\na = []\n",
    )
    .unwrap();
    std::fs::write(
        app.join("Cargo.toml"),
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\nlicense = \"Apache-2.0\"\n\n[dependencies]\nmy-lib = { path = \"../lib\", features = [\"a\"] }\n",
    )
    .unwrap();
    let lock = Command::new("cargo")
        .args(["generate-lockfile"])
        .current_dir(&app)
        .output()
        .unwrap();
    assert!(lock.status.success(), "{}", String::from_utf8_lossy(&lock.stderr));
    for fmt in ["{lib}", "{p} {l} {r}", "{lib} [{f}]"] {
        let cargo = Command::new("cargo")
            .args(["tree", "--charset", "ascii", "--format", fmt])
            .current_dir(&app)
            .output()
            .unwrap();
        let rb = Command::new(env!("CARGO_BIN_EXE_rb"))
            .args(["tree", "--charset", "ascii", "--format", fmt, "--offline", "--color", "never"])
            .current_dir(&app)
            .env("RB_HOME", root.join("home"))
            .env("RB_STORE_DIR", root.join("store"))
            .env("RB_COMPACT", "off")
            .output()
            .unwrap();
        let cargo_text = String::from_utf8_lossy(&cargo.stdout);
        let rb_text = String::from_utf8_lossy(&rb.stdout);
        assert!(cargo.status.success(), "{fmt}: {}", String::from_utf8_lossy(&cargo.stderr));
        assert!(rb.status.success(), "{fmt}: {}\n{rb_text}", String::from_utf8_lossy(&rb.stderr));
        assert_eq!(
            rb_text.trim(),
            cargo_text.trim(),
            "format {fmt}\nrb:\n{rb_text}\ncargo:\n{cargo_text}"
        );
    }
    let bad = Command::new(env!("CARGO_BIN_EXE_rb"))
        .args(["tree", "--format", "{nope}", "--offline", "--color", "never"])
        .current_dir(&app)
        .env("RB_HOME", root.join("home"))
        .env("RB_STORE_DIR", root.join("store"))
        .env("RB_COMPACT", "off")
        .output()
        .unwrap();
    assert!(!bad.status.success());
    let err = String::from_utf8_lossy(&bad.stderr);
    assert!(err.contains("unsupported pattern `nope`"), "{err}");
}

