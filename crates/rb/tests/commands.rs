//! `run`, `test`, `bench`, and `doc` on the offline `testing` fixture

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

struct Project {
    _dir: tempfile::TempDir,
    root: PathBuf,
}

fn copy_dir(from: &Path, to: &Path) {
    std::fs::create_dir_all(to).unwrap();
    for e in std::fs::read_dir(from).unwrap() {
        let e = e.unwrap();
        let dst = to.join(e.file_name());
        if e.file_type().unwrap().is_dir() {
            if e.file_name() != "target" {
                copy_dir(&e.path(), &dst);
            }
        } else {
            std::fs::copy(e.path(), dst).unwrap();
        }
    }
}

impl Project {
    fn testing() -> Self {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().canonicalize().unwrap();
        let fixture = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/compat/fixtures/testing");
        copy_dir(&fixture, &root.join("ws"));
        Self { _dir: dir, root }
    }

    fn ws(&self) -> PathBuf {
        self.root.join("ws")
    }

    fn rb(&self, args: &[&str]) -> Output {
        Command::new(env!("CARGO_BIN_EXE_rb"))
            .arg(args[0])
            .args(["--color", "never"])
            .args(&args[1..])
            .current_dir(self.ws())
            .env("RB_HOME", self.root.join("home"))
            .env("RB_STORE_DIR", self.root.join("store"))
            .env("RB_COMPACT", "sync")
            .env_remove("RUSTC_WRAPPER")
            .output()
            .unwrap()
    }

    /// Runs rb, asserting success; returns stdout + stderr
    fn ok(&self, args: &[&str]) -> String {
        let out = self.rb(args);
        let text = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
        assert!(out.status.success(), "rb {args:?} failed:\n{text}");
        text
    }
}

